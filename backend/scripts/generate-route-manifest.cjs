const fs = require("fs");
const path = require("path");

const backendRoot = path.resolve(__dirname, "..");
const apiRoot = path.join(backendRoot, "app", "api");
const outputPath = path.join(backendRoot, "lib", "generated-route-manifest.js");

function toPosix(value) {
  return value.replace(/\\/g, "/");
}

function getRouteEntries(dir) {
  const entries = [];

  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      entries.push(...getRouteEntries(fullPath));
      continue;
    }

    if (entry.name !== "route.js") {
      continue;
    }

    const relativePath = toPosix(path.relative(apiRoot, fullPath));
    const importPath = `../app/api/${relativePath}`;
    const apiPath = `/api/${relativePath.replace(/\/route\.js$/, "").replace(/(^|\/)\[(.+?)\]/g, (_, slash, segment) => `${slash}:${segment}`)}`;
    const segments = apiPath.split("/").filter(Boolean);
    const score = segments.reduce((total, segment) => total + (segment.startsWith(":") ? 1 : 10), 0);

    entries.push({
      importPath,
      apiPath,
      score,
      relativePath,
    });
  }

  return entries.sort((a, b) => b.score - a.score || a.apiPath.localeCompare(b.apiPath));
}

function buildManifestSource(entries) {
  // Static imports, not lazy import() calls. Vercel's file tracer does not follow
  // the dynamic imports into the serverless bundle, so the route modules were left
  // out of the function and every request failed on import before reaching a
  // handler. Static imports are always traced, which guarantees they ship.
  const importLines = entries.map(
    (entry, index) => `import * as route${index} from ${JSON.stringify(entry.importPath)};`,
  );

  const routeLines = entries.map(
    (entry, index) =>
      `  { pattern: ${JSON.stringify(entry.apiPath)}, score: ${entry.score}, filePath: ${JSON.stringify(entry.relativePath)}, module: route${index}, load: () => import(${JSON.stringify(entry.importPath)}) },`,
  );

  return `// This file is auto-generated by scripts/generate-route-manifest.cjs.
// Do not edit manually.
${importLines.join("\n")}

export const GENERATED_ROUTES = [
${routeLines.join("\n")}
];
`;
}

const entries = getRouteEntries(apiRoot);
fs.writeFileSync(outputPath, buildManifestSource(entries));
console.log(`Generated route manifest with ${entries.length} routes at ${path.relative(backendRoot, outputPath)}`);
